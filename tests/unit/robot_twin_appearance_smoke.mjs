import assert from 'node:assert/strict';
import * as THREE from 'three';
import { tintRobotTwinBody, isRobotTwinBodyMesh, robotTwinColor } from "../../src/features/robot-twin/model/robotTwinAppearance.js";

const robot = new THREE.Group(), bodyLink = new THREE.Group(), visual = new THREE.Group();
bodyLink.name = 'waist_yaw_L'; bodyLink.userData.urdfType = 'link'; visual.userData.urdfType = 'visual';
robot.add(bodyLink); bodyLink.add(visual);
const shared = new THREE.MeshStandardMaterial({ color: '#e0e0e0', roughness: 0.65 });
const geometry = new THREE.BoxGeometry();
const body = new THREE.Mesh(geometry, shared); body.name = 'body'; visual.add(body);
const flange = new THREE.Group(), toolVisual = new THREE.Group();
flange.name = 'third-party-flange'; flange.userData = { urdfType: 'link', endEffectorSide: 'left' };
bodyLink.add(flange); flange.add(toolVisual); toolVisual.userData.urdfType = 'visual';
const tool = new THREE.Mesh(geometry, shared); tool.name = 'vendor-tool'; toolVisual.add(tool);
assert.equal(isRobotTwinBodyMesh(body), true); assert.equal(isRobotTwinBodyMesh(tool), false);
const a = tintRobotTwinBody(robot, '#62c7a0');
assert.equal(body.material.color.getHexString(), '62c7a0');
assert.equal(tool.material, shared, 'tool materials stay identical even when shared with body meshes');
assert.equal(shared.color.getHexString(), 'e0e0e0'); assert.equal(body.material.roughness, 0.65);
const second = robot.clone(true), b = tintRobotTwinBody(second, '#6baff2');
assert.equal(second.getObjectByName('body').material.color.getHexString(), '6baff2');
assert.equal(body.material.color.getHexString(), '62c7a0', 'robot colors are independent');
assert.equal(second.getObjectByName('vendor-tool').material, shared);
assert.equal(second.getObjectByName('vendor-tool').material.color.getHexString(), 'e0e0e0');
const standalone = new THREE.Mesh(geometry, shared);
assert.equal(isRobotTwinBodyMesh(standalone), false, 'do not recolor indivisible models with unknown tool boundaries');
let disposedOriginal = false; shared.addEventListener('dispose', () => { disposedOriginal = true; });
b.dispose(); a.dispose();
assert.equal(disposedOriginal, false); assert.equal(body.material, shared); assert.equal(tool.material, shared);
const used = new Set();
for (let index = 0; index < 16; index++) used.add(robotTwinColor(`robot-${index}`, used));
assert.equal(used.size, 16);
assert.equal(robotTwinColor('persistent-card'), robotTwinColor('persistent-card'));
geometry.dispose(); shared.dispose();
console.log('robot twin appearance: independent body colors, external tool preservation and original material restoration passed');

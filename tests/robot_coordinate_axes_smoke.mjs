import assert from 'node:assert/strict';
import * as THREE from 'three';
import { createRobotCoordinateAxes, getRobotCoordinateFrames, updateRobotCoordinateAxes, clearRobotCoordinateAxes } from "../src/features/robot/model/robotCoordinateAxes.js";
import { serializeMobileTeachingRobot } from "../src/features/teaching/mobile/model/mobileTeachingKinematics.js";

const layer = new THREE.Group(), robot = new THREE.Group(); layer.add(robot);
layer.position.set(1, -2, .3); layer.rotation.z = .6;
const link = (name, parent) => {
  const frame = new THREE.Group(); frame.name = name; frame.userData.urdfType = 'link'; parent.add(frame); return frame;
};
const base = link('base_link', robot), waist = link('waist_yaw_L', base);
waist.position.z = 1;
const joint = new THREE.Group(); joint.name = 'left_J1'; joint.userData.urdfType = 'joint';
joint.userData.jointType = 'revolute'; joint.userData.jointAxis = [0, 0, 1]; waist.add(joint);
const arm = link('left_L1', joint); arm.position.x = .5;
const optical = link('zivid_left_optical_frame', arm); optical.rotation.y = Math.PI / 2;
optical.position.z = .2;
const right = link('zivid_right_optical_frame', waist); right.position.y = -.6;
const visual = new THREE.Mesh(new THREE.BoxGeometry(.1, .2, .3), new THREE.MeshBasicMaterial());
visual.name = 'helper-not-a-coordinate'; arm.add(visual);
const frames = getRobotCoordinateFrames(robot);
assert.deepEqual(frames.map(frame => frame.name), ['base_link', 'waist_yaw_L', 'left_L1', 'zivid_left_optical_frame', 'zivid_right_optical_frame']);
assert.deepEqual(frames.map(frame => frame.group), ['chassis', 'torso', 'left', 'camera', 'camera']);
assert.equal(frames.find(frame => frame.name === 'left_L1').jointName, 'left_J1');
const camera = new THREE.PerspectiveCamera(45, 1, .01, 100);
camera.position.set(5, -6, 5); camera.lookAt(0, 0, 1); camera.updateMatrixWorld(true);
const canvas = { clientHeight: 700, dataset: {} };
const display = createRobotCoordinateAxes();
const update = names => updateRobotCoordinateAxes(display, robot, camera, canvas, new Set(names));
const snapshot = () => JSON.stringify(serializeMobileTeachingRobot(robot, { includeCollision: true, includeCollisionHulls: true }));
const before = snapshot();
update([]);
assert.equal(canvas.dataset.robotCoordinateAxesCount, '0');
assert.equal(display.markers.size, 0, 'default-off must not allocate marker meshes or textures');
update(frames.map(frame => frame.name));
assert.equal(canvas.dataset.robotCoordinateAxesCount, '5');
assert.equal(canvas.dataset.zividOpticalAxesCount, '2');
assert.equal(snapshot(), before, 'guides must not enter robot bounds, picking or planner/collision snapshots');
assert.equal(display.root.parent, null);
const marker = display.markers.get('left_L1');
assert.ok(marker.position.distanceTo(arm.getWorldPosition(new THREE.Vector3())) < 1e-10);
const original = marker.position.clone();
layer.visible = false; joint.rotation.z = .2; layer.rotation.z = -.4;
update(['left_L1', 'zivid_left_optical_frame']);
assert.equal(canvas.dataset.robotCoordinateAxesCount, '2');
assert.equal(canvas.dataset.zividOpticalAxesCount, '1');
assert.equal(canvas.dataset.zividRightAxesVisible, 'false');
assert.equal(canvas.dataset.zividRightAxesPosition, undefined);
assert.ok(marker.position.distanceTo(original) > .1);
assert.ok(marker.position.distanceTo(arm.getWorldPosition(new THREE.Vector3())) < 1e-10, 'hidden robot frames still follow base and joints');
assert.ok(marker.quaternion.angleTo(arm.getWorldQuaternion(new THREE.Quaternion())) < 1e-7);
const expectedForward = new THREE.Vector3(0, 0, 1).applyQuaternion(optical.getWorldQuaternion(new THREE.Quaternion()));
assert.ok(new THREE.Vector3(...canvas.dataset.zividLeftAxesForward.split(',').map(Number)).distanceTo(expectedForward) < 1e-7);
const hits = new THREE.Raycaster(new THREE.Vector3(0, 0, 10), new THREE.Vector3(0, 0, -1)).intersectObject(display.root, true);
assert.deepEqual(hits, [], 'coordinate guides must not intercept surface clicks');
const scale = marker.scale.x;
camera.zoom = 2; camera.updateProjectionMatrix(); update(['left_L1']);
assert.ok(Math.abs(marker.scale.x * 2 - scale) < 1e-10, 'axes keep a stable screen size on zoom');
update([]);
assert.equal(display.root.visible, false);
assert.ok([...display.markers.values()].every(item => !item.visible));
const geometry = marker.children[0].children[0].geometry;
let disposed = false; geometry.addEventListener('dispose', () => { disposed = true; });
const replacement = new THREE.Group(); replacement.name = 'plain-mesh';
updateRobotCoordinateAxes(display, replacement, camera, canvas, new Set(['left_L1']));
assert.equal(disposed, true, 'changing models releases old guides');
assert.equal(display.markers.size, 0);
assert.equal(canvas.dataset.robotCoordinateAxesCount, '0');
assert.equal(getRobotCoordinateFrames(replacement)[0].label, '模型原点');
updateRobotCoordinateAxes(display, null, camera, canvas, new Set());
assert.equal(display.frames.length, 0);
clearRobotCoordinateAxes(display);
visual.geometry.dispose(); visual.material.dispose();
console.log('Robot coordinate axes: default-off, real link frames, selective/full display, moving and hidden robot transforms, optical direction, screen size, interaction isolation and resource cleanup passed.');
